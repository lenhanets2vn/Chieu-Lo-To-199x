const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'src/App.tsx'), 'utf8');
const match = src.match(/const secondsUntilRound = \(deadline: number, now: number = Date\.now\(\)\): number \| null => \{[\s\S]*?\n\};/);
assert(match, 'Shared countdown helper not found');
const js = ts.transpileModule(`${match[0]}\nmodule.exports = secondsUntilRound;`, { compilerOptions: {target:ts.ScriptTarget.ES2022, module:ts.ModuleKind.CommonJS}}).outputText;
const ctx = { module:{exports:null}, Date, Number, Math }; vm.runInNewContext(js,ctx);
const remaining = ctx.module.exports;
assert.equal(remaining(20_000,10_000),10);
assert.equal(remaining(20_000,19_001),1);
assert.equal(remaining(20_000,20_000),null);
assert.equal(remaining(20_000,20_001),null);
assert.equal(remaining(20_000,50_000),null);
assert.equal(remaining(NaN,20_000),null);
assert(src.includes("startCountdownLeft !== null && startCountdownLeft > 0 && ("), 'Do not show zero seconds');
assert(src.includes("gameState === 'COUNTDOWN' && startCountdownLeft !== null && !selectionLocked"), 'Ticket picker must close at countdown expiry');
assert(src.includes('setStartCountdownLeft(secondsUntilRound(state.countdownEndsAt));'), 'Snapshot must hide expired countdown');
assert(src.includes('setStartCountdownLeft(secondsUntilRound(deadline));'), 'Clock tick must hide expired countdown');
console.log('PASS: guest countdown hides at zero; ticket selection closes; expiry uses shared deadline without Firestore writes');
